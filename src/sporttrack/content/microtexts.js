// Сообщение дня: меняется раз в сутки, не «прыгает» при перерисовке
export function motivationOfTheDay(date = new Date()) {
  const dayNumber = Math.floor(date.getTime() / 86_400_000);
  return motivation[dayNumber % motivation.length];
}

// Сообщение после действия: берём по порядковому номеру
export const motivationAt = (index) => motivation[Math.abs(index) % motivation.length];
